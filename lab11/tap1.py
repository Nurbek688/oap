# кітап жанрдардың списогы
janr = [
    "Роман", "Фантастика", "Роман", "Детектив", "Фантастика", 
    "Поэзия", "Роман", "Детектив", "Тарих", "Фантастика"
]
# База данных 
books_information = [
    {"кітап атауы": "Абай жолы", "жанры": "Роман", "жылы": 1942},
    {"кітап атауы": "Болашақ хроникасы", "жанры": "Фантастика", "жылы": 2022},
    {"кітап атауы": "Көксерек", "жанры": "Повесть", "жылы": 1929},
    {"кітап атауы": "Жаңа дәуір", "жанры": "Роман", "жылы": 2024}
]
print('\n ====== Ә Тапсырмасы Дубликат өшірілуі ====== \n')
unique = set(janr)
print('Бірегей жанрлар:', unique)

# Элемент және дубликаттар саны
all_count = len(janr)
unique_count = len(unique)
different_count = all_count - unique_count
print('Жалпы элементтер саны:', all_count)
print('Бірегей саны:', unique_count)
print('Қайталану саны:', different_count)
print('\n ===== Жиілік =====')

# Бос сөздік қосамыз
frequency = {}
for i in janr:
    frequency[i] = frequency.get(i, 0) + 1 # get сөздікте жанр болмаса 0 алады
print('Жиілік сөздігі:', frequency)

print('\n======= Б Тапсырмасы Іздеу және Өзгерту ========')
# фильтр: 2020 жылдан кейін шыққан кітаптарды шығару
print('2020 ж-дан кейін шыққан кітаптар')
for book in books_information:
    if book['жылы'] > 2020:
        print(book['кітап атауы'], book['жылы'])
#  жаңа дәуір 2024-2025 жылдары шыққан кітаптарды шығару
print('\n========Деректерді жаңарту========')
for book in books_information:
    if book['кітап атауы'] == 'Жаңа дәуір':
        print('Ескі жылы:', book['жылы'])
        book['жылы'] = 2025
        print('Жаңа жылы:', book['жылы'])

print('\n======= Жоқ кілтті іздеу ========')
for book in books_information:
    author_info = book.get('автор', 'Автор туралы ақпарат жоқ')
    print('Кітап атауы:', book['кітап атауы'], '| Автор:', author_info)

print('\n======= B Тапсырмасы Бос деректерді тексеру ========')
