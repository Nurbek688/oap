def selection_sort(data): #def selection_sort функциясы берілген тізімді сұрыптайды және салыстырулар мен алмастыруларды санайды
    a=data.copy() #a переменнасына берілген тізімнің копиясын сақтаймыз
    comp=swap=0 #comp және swap переменналарын 0-ге теңестіреміз
    for i in range(len(a)-1): #for циклін қолдана отырып, тізімнің әр элементін қарастырамыз  
        m=i #m переменнасын i-ге теңестіреміз, яғни ең кіші элементтің индексін сақтаймыз
        for j in range(i+1, len(a)): #for циклін қолдана отырып, i-ден кейінгі элементтерді қарастырамыз
            comp+=1 #comp переменнасын 1-ге арттырамыз, яғни салыстыру санын есептейміз
            if a[j]<a[m]: #if шартын қолдана отырып, егер a[j] элементі a[m] элементінен кіші болса
                m=j #m переменнасын j-ге теңестіреміз, яғни ең кіші элементтің индексін жаңартамыз
        if m!=i: #if шартын қолдана отырып, егер m i-ге тең болмаса, яғни ең кіші элементтің индексі өзгерген болса
            a[i], a[m]=a[m], a[i] #a[i] және a[m] элементтерін алмастырамыз
            swap+=1 #swap переменнасын 1-ге арттырамыз, яғни алмастыру санын есептейміз
    return comp, swap #return операторын қолдана отырып, салыстырулар мен алмастыруларды қайтарамыз


def insertion_sort(data): #insertion_sort функциясы берілген тізімді сұрыптайды және салыстырулар мен орын ауыстыруларды санайды
    a=data.copy() #a переменнасына берілген тізімнің копиясын сақтаймыз
    comp=shift=0 #comp және shift переменналарын 0-ге теңестіреміз
    for i in range(1, len(a)): #for циклін қолдана отырып, тізімнің әр элементін қарастырамыз, 1-ден бастап
        key=a[i] #key переменнасын a[i] элементіне теңестіреміз, яғни сұрыпталатын элементті сақтаймыз
        j=i-1 #j переменнасын i-1-ге теңестіреміз, яғни сұрыпталған бөліктің соңғы элементінің индексін сақтаймыз
        while j>=0: #while циклін қолдана отырып, j 0-ден үлкен немесе тең болғанша қайталаймыз
            comp+=1 #comp переменнасын 1-ге арттырамыз, яғни салыстыру санын есептейміз
            if a[j]<=key: #if шартын қолдана отырып, егер a[j] элементі key элементінен кіші немесе тең болса 
                break #break операторын қолдана отырып, циклдан шығамыз
            a[j+1]=a[j] #a[j + 1] элементін a[j] элементіне теңестіреміз
            shift+=1 #shift переменнасын 1-ге арттырамыз, яғни орын ауыстыру санын есептейміз
            j-=1 #j переменнасын 1-ге азайтамыз, яғни сұрыпталған бөліктің соңғы элементінің индексін жаңартамыз
        a[j+1]=key #a[j + 1] элементін key элементіне теңестіреміз, яғни сұрыпталатын элементті дұрыс орынға қоямыз
    return comp, shift #return операторын қолдана отырып, салыстырулар мен орын ауыстыруларды қайтарамыз


def bubble_sort(data): #bubble _sort функциясы берілген тізімді сұрыптайды және салыстырулар мен алмастыруларды санайды
    a=data.copy() #a переменнасына берілген тізімнің копиясын сақтаймыз
    comp=swap=0 #comp және swap переменналарын 0-ге теңестіреміз
    for i in range(len(a)-1): #for циклін қолдана отырып, тізімнің әр элементін қарастырамыз
        changed=False #changed переменнасын False-ге теңестіреміз, яғни алмастыру болғанын тексереміз
        for j in range(len(a)-1-i): #for циклін қолдана отырып, тізімнің әр элементін қарастырамыз, бірақ соңғы i элементтерін елемейміз
            comp += 1 #comp переменнасын 1-ге арттырамыз, яғни салыстыру санын есептейміз
            if a[j] > a[j + 1]: #if шартын қолдана отырып, егер a[j] элементі a[j + 1] элементінен үлкен болса
                a[j], a[j + 1] = a[j + 1], a[j] #a[j] және a[j + 1] элементтерін алмастырамыз
                swap += 1 #swap переменнасын 1-ге арттырамыз, яғни алмастыру санын есептейміз
                changed = True #changed переменнасын True-ге теңестіреміз, яғни алмастыру болғанын белгілейміз
        if not changed: #if шартын қолдана отырып, егер changed False болса, яғни алмастыру болмаған болса 
            break #break операторын қолдана отырып, циклдан шығамыз
    return comp, swap #return операторын қолдана отырып, салыстырулар мен алмастыруларды қайтарамыз

